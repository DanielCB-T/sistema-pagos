-- Sistema de Gestión de Pagos - Asamblea Comunitaria San Juan Teponaxtla
-- Esquema PostgreSQL (>= 12). Basado en el Modelo Relacional del protocolo.
--
-- Uso:
--   createdb sistema_pagos
--   psql -d sistema_pagos -f database/schema.sql
-- Solo contiene estructura (sin datos). Los roles y el usuario
-- administrador inicial los crea:  npm run seed  (carpeta backend)
-- =====================================================================
BEGIN;

-- ---------- ROL ------------------------------------------------------
CREATE TABLE rol (
    id_rol      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol  VARCHAR(50) NOT NULL UNIQUE
);

-- ---------- USUARIO (Rol 1:N Usuario) --------------------------------
-- Nota: la columna "contraseña" del diagrama se llama "contrasena"
-- (sin ñ) para evitar problemas de codificación/quoting. Guarda hash bcrypt.
CREATE TABLE usuario (
    id_usuario      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario  VARCHAR(50)  NOT NULL UNIQUE,
    contrasena      VARCHAR(100) NOT NULL,
    estado          VARCHAR(20)  NOT NULL DEFAULT 'activo'
                    CHECK (estado IN ('activo', 'bloqueado')),
    id_rol          INT NOT NULL
                    REFERENCES rol (id_rol) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE INDEX idx_usuario_rol ON usuario (id_rol);

-- ---------- HABITANTE ------------------------------------------------
CREATE TABLE habitante (
    id_habitante     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo  VARCHAR(100) NOT NULL,
    direccion        TEXT,
    telefono         VARCHAR(15),
    numero_familia   VARCHAR(20)
);
CREATE INDEX idx_habitante_nombre ON habitante (lower(nombre_completo));
CREATE INDEX idx_habitante_familia ON habitante (numero_familia);

-- ---------- ADEUDO (Habitante 1:N Adeudo) ----------------------------
CREATE TABLE adeudo (
    id_adeudo        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monto_total      DECIMAL(10,2) NOT NULL CHECK (monto_total > 0),
    monto_pagado     DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (monto_pagado >= 0),
    monto_pendiente  DECIMAL(10,2) NOT NULL,
    estado           VARCHAR(20)   NOT NULL DEFAULT 'pendiente'
                     CHECK (estado IN ('pendiente', 'parcial', 'pagado')),
    id_habitante     INT NOT NULL
                     REFERENCES habitante (id_habitante) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_adeudo_saldos CHECK (
        monto_pagado <= monto_total
        AND monto_pendiente = monto_total - monto_pagado
    )
);
CREATE INDEX idx_adeudo_habitante ON adeudo (id_habitante);
CREATE INDEX idx_adeudo_estado ON adeudo (estado);

-- ---------- PAGO (Habitante 1:N Pago, Usuario 1:N Pago, Adeudo 1:N Pago)
-- id_adeudo es opcional: permite aportaciones voluntarias sin adeudo.
CREATE TABLE pago (
    id_pago        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monto          DECIMAL(10,2) NOT NULL CHECK (monto > 0),
    concepto       VARCHAR(100)  NOT NULL,
    fecha          DATE          NOT NULL DEFAULT CURRENT_DATE,
    observaciones  TEXT,
    id_habitante   INT NOT NULL
                   REFERENCES habitante (id_habitante) ON UPDATE CASCADE ON DELETE RESTRICT,
    id_usuario     INT NOT NULL
                   REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    id_adeudo      INT
                   REFERENCES adeudo (id_adeudo) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE INDEX idx_pago_habitante ON pago (id_habitante);
CREATE INDEX idx_pago_usuario   ON pago (id_usuario);
CREATE INDEX idx_pago_adeudo    ON pago (id_adeudo);
CREATE INDEX idx_pago_fecha     ON pago (fecha);

-- ---------- REPORTE (Usuario 1:N Reporte) ----------------------------
-- fecha_inicio / fecha_fin son opcionales: solo aplican a reportes por periodo.
CREATE TABLE reporte (
    id_reporte        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_reporte      VARCHAR(50) NOT NULL,
    fecha_inicio      DATE,
    fecha_fin         DATE,
    fecha_generacion  DATE NOT NULL DEFAULT CURRENT_DATE,
    id_usuario        INT NOT NULL
                      REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_reporte_rango CHECK (
        fecha_inicio IS NULL OR fecha_fin IS NULL OR fecha_fin >= fecha_inicio
    )
);
CREATE INDEX idx_reporte_usuario ON reporte (id_usuario);

COMMIT;
